/**
 * Builds a redacted, serializable incident report from a run and its
 * analysis. Both the JSON and Markdown exports are rendered from this one
 * structure, so they always agree and are redacted identically.
 */
import type { ImportOrigin, LoadedRun, RunSource } from '../data/types';
import { isJsonValue } from '../data/validate';
import { computeRunFacts } from '../diagnostics/facts';
import type { RunCounts, RunFacts } from '../diagnostics/facts';
import type {
  Confidence,
  DiagnosisResult,
  Evidence,
  FindingImpact,
  FindingReview,
  RuleId,
} from '../diagnostics/types';
import { msBetween } from '../domain/format';
import { getEventTitle } from '../domain/labels';
import { toPlainText } from '../domain/richText';
import type { RichText } from '../domain/richText';
import { findTerminalError } from '../domain/runIndex';
import type { AgentEvent, JsonObject, JsonValue, RunStatus } from '../domain/types';
import type { ClaimKind, Grounding } from '../model/output';
import type { SummaryResult } from '../model/summarize';
import { createRedactor } from './redact';
import type { Redactor } from './redact';

export const REPORT_SCHEMA_VERSION = 2;

export const HEURISTIC_DISCLAIMER =
  'Findings are heuristics produced by deterministic rules from the recorded events. They point to likely failure points and are not confirmed root causes.';

export const REDACTION_NOTICE =
  'Values that look like API keys, bearer tokens, passwords, and common secret assignments were replaced with [REDACTED]. Redaction is best-effort: review the report before sharing it.';

export const EXAMPLE_NOTICE =
  'This run is a fictional example bundled with Agent Incident Investigator. It is not a real incident and does not describe real customers or systems.';

export const MODEL_NOTICE =
  'Generated by a local language model from the redacted trace. It is unverified: check every claim against the cited events.';

export interface ReportFinding {
  id: string;
  rule: RuleId;
  title: string;
  impact: FindingImpact;
  confidence: Confidence;
  confidenceReason: string;
  observed: RichText;
  interpretation: RichText;
  suggestion: RichText;
  primaryEventId: string;
  evidence: Evidence[];
  review: FindingReview | 'open';
}

export interface ReportModelSummary {
  model: string;
  runtime: 'Ollama';
  runtimeVersion?: string;
  generatedAt: string;
  summary: RichText;
  claims: Array<{
    kind: ClaimKind;
    statement: string;
    eventIds: string[];
    unknownIds: string[];
    grounded: boolean;
  }>;
  insufficientEvidence: boolean;
  nextCheck: string;
  grounding: Grounding;
}

export interface IncidentReport {
  generatedAt: string;
  source: RunSource;
  origin?: ImportOrigin;
  run: {
    id: string;
    agentName: string;
    agentVersion?: string;
    task: string;
    summary: string;
    status: RunStatus;
    startedAt: string;
    endedAt: string;
    durationMs?: number;
    eventCount: number;
    metadata: JsonObject;
  };
  observed: {
    stop?: {
      eventId: string;
      title: string;
      afterEventId?: string;
      afterTitle?: string;
      gapMs?: number;
    };
    counts: RunCounts;
    longestGap?: { fromEventId: string; toEventId: string; ms: number };
  };
  terminalError?: { eventId: string; type: string; message: string };
  findings: ReportFinding[];
  modelSummary?: ReportModelSummary;
  events: AgentEvent[];
  dataQuality: {
    skippedRecords: Array<{ index: number; id?: string; issues: string[]; raw?: JsonValue }>;
    warnings: string[];
    ruleFailures: string[];
  };
  redactedValueCount: number;
}

export interface ReportOptions {
  generatedAt?: Date;
  facts?: RunFacts;
  /** The developer's review of each finding, keyed by finding ID. */
  reviews?: ReadonlyMap<string, FindingReview>;
  /** Included, clearly labelled, when a local-model summary was generated. */
  modelSummary?: SummaryResult;
}

function redactEvent(event: AgentEvent, redactor: Redactor): AgentEvent {
  const redacted = { ...event, metadata: redactor.object(event.metadata) };
  if (event.input !== undefined) redacted.input = redactor.json(event.input);
  if (event.output !== undefined) redacted.output = redactor.json(event.output);
  if (event.name !== undefined) redacted.name = redactor.text(event.name);
  switch (redacted.kind) {
    case 'agent_message':
      redacted.text = redactor.text(redacted.text);
      break;
    case 'tool_result':
      if (redacted.errorMessage) redacted.errorMessage = redactor.text(redacted.errorMessage);
      break;
    case 'retry':
      redacted.reason = redactor.text(redacted.reason);
      break;
    case 'error':
      redacted.message = redactor.text(redacted.message);
      break;
    case 'permission_decision':
      redacted.action = redactor.text(redacted.action);
      if (redacted.reason) redacted.reason = redactor.text(redacted.reason);
      break;
    case 'tool_call':
      break;
  }
  return redacted;
}

function reportModelSummary(result: SummaryResult, redactor: Redactor): ReportModelSummary {
  const { summary } = result;
  return {
    model: result.model.name,
    runtime: 'Ollama',
    ...(result.runtimeVersion && { runtimeVersion: result.runtimeVersion }),
    generatedAt: result.generatedAt,
    summary: redactor.rich(summary.summary),
    claims: summary.claims.map((claim) => ({
      kind: claim.kind,
      statement: redactor.text(claim.statement),
      eventIds: claim.eventIds,
      unknownIds: claim.unknownIds.map((id) => redactor.text(id)),
      grounded: claim.grounded,
    })),
    insufficientEvidence: summary.insufficientEvidence,
    nextCheck: redactor.text(summary.nextCheck),
    grounding: summary.grounding,
  };
}

export function buildIncidentReport(
  loaded: LoadedRun,
  diagnosis: DiagnosisResult,
  options: ReportOptions = {},
): IncidentReport {
  const redactor = createRedactor();
  const { run } = loaded;
  const terminal = findTerminalError(run);
  const durationMs = msBetween(run.startedAt, run.endedAt);
  const facts = options.facts ?? computeRunFacts(run);
  const title = (event: AgentEvent) => redactor.text(getEventTitle(event));

  const report: Omit<IncidentReport, 'redactedValueCount'> = {
    generatedAt: (options.generatedAt ?? new Date()).toISOString(),
    source: loaded.source,
    ...(loaded.origin && {
      origin: { ...loaded.origin, fileName: redactor.text(loaded.origin.fileName) },
    }),
    run: {
      id: run.id,
      agentName: run.agentName,
      ...(run.agentVersion !== undefined && { agentVersion: run.agentVersion }),
      task: redactor.text(run.task),
      summary: redactor.text(run.summary),
      status: run.status,
      startedAt: run.startedAt,
      endedAt: run.endedAt,
      ...(durationMs !== undefined && durationMs >= 0 && { durationMs }),
      eventCount: run.events.length,
      metadata: redactor.object(run.metadata),
    },
    observed: {
      ...(facts.stop && {
        stop: {
          eventId: facts.stop.terminal.id,
          title: title(facts.stop.terminal),
          ...(facts.stop.after && {
            afterEventId: facts.stop.after.id,
            afterTitle: title(facts.stop.after),
          }),
          ...(facts.stop.gapMs !== undefined && { gapMs: facts.stop.gapMs }),
        },
      }),
      counts: facts.counts,
      ...(facts.longestGap && {
        longestGap: {
          fromEventId: facts.longestGap.from.id,
          toEventId: facts.longestGap.to.id,
          ms: facts.longestGap.ms,
        },
      }),
    },
    ...(terminal?.kind === 'error' && {
      terminalError: {
        eventId: terminal.id,
        type: terminal.errorType,
        message: redactor.text(terminal.message),
      },
    }),
    findings: diagnosis.findings.map((finding) => ({
      id: finding.id,
      rule: finding.ruleId,
      title: redactor.text(finding.title),
      impact: finding.impact,
      confidence: finding.confidence,
      confidenceReason: redactor.text(finding.confidenceReason),
      observed: redactor.rich(finding.observed),
      interpretation: redactor.rich(finding.interpretation),
      suggestion: redactor.rich(finding.suggestion),
      primaryEventId: finding.primaryEventId,
      evidence: finding.evidence.map((item) => ({ ...item, note: redactor.text(item.note) })),
      review: options.reviews?.get(finding.id) ?? 'open',
    })),
    ...(options.modelSummary && {
      modelSummary: reportModelSummary(options.modelSummary, redactor),
    }),
    events: run.events.map((event) => redactEvent(event, redactor)),
    dataQuality: {
      skippedRecords: loaded.skipped.map((record) => ({
        index: record.index,
        ...(record.id !== undefined && { id: redactor.text(record.id) }),
        issues: record.issues.map((issue) => redactor.text(`${issue.path} ${issue.message}`)),
        ...(isJsonValue(record.raw) && { raw: redactor.json(record.raw) }),
      })),
      warnings: loaded.warnings.map((issue) => redactor.text(`${issue.path} ${issue.message}`)),
      ruleFailures: diagnosis.ruleFailures.map(
        (failure) => `${failure.ruleId}: ${redactor.text(failure.message)}`,
      ),
    },
  };
  return { ...report, redactedValueCount: redactor.count };
}

/** Plain JSON document for the JSON export; rich text becomes plain strings. */
export function renderJsonReport(report: IncidentReport): string {
  const document = {
    schemaVersion: REPORT_SCHEMA_VERSION,
    generator: 'Agent Incident Investigator',
    generatedAt: report.generatedAt,
    source: report.source,
    ...(report.source === 'example' && { exampleNotice: EXAMPLE_NOTICE }),
    ...(report.origin && { origin: report.origin }),
    disclaimer: HEURISTIC_DISCLAIMER,
    redaction: { notice: REDACTION_NOTICE, redactedValueCount: report.redactedValueCount },
    run: report.run,
    observed: report.observed,
    terminalError: report.terminalError ?? null,
    findings: report.findings.map((finding) => ({
      ...finding,
      observed: toPlainText(finding.observed),
      interpretation: toPlainText(finding.interpretation),
      suggestion: toPlainText(finding.suggestion),
    })),
    ...(report.modelSummary && {
      modelSummary: {
        notice: MODEL_NOTICE,
        ...report.modelSummary,
        summary: toPlainText(report.modelSummary.summary),
      },
    }),
    events: report.events,
    dataQuality: report.dataQuality,
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}
